import re
import shutil
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

from sitekit import checks as _checks  # noqa: E402
from sitekit import reference as _reference  # noqa: E402
from sitekit.markdown import PageRenderer, inline, slugify  # noqa: E402
from sitekit.media import MediaLibrary  # noqa: E402

CONTENT = ROOT / "content"
TEMPLATES = ROOT / "templates"
STATIC = ROOT / "static"
MEDIA = ROOT / "media"
DATA = ROOT / "data"
OUT = ROOT / "_site"


@dataclass
class Page:
    url: str                     # "learn/03-scanning/" ("" for home)
    source: Path
    meta: dict
    body_md: str
    section: Optional[str] = None
    html: str = ""
    toc: list = field(default_factory=list)
    ids: set = field(default_factory=set)
    text: str = ""

    @property
    def title(self) -> str:
        return self.meta.get("title", "")

    @property
    def nav_title(self) -> str:
        return self.meta.get("nav", self.title)


def read_page(path: Path) -> tuple[dict, str]:
    raw = path.read_text(encoding="utf-8")
    if raw.startswith("---\n"):
        end = raw.index("\n---\n", 4)
        meta = _front_matter(raw[4:end])
        body = raw[end + 5:]
    else:
        meta, body = {}, raw
    return meta, body


def _front_matter(text: str) -> dict:
    """One ``key: value`` per line (values may hold colons); numbers and
    true/false become values, anything else stays text."""
    meta = {}
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, _, value = line.partition(":")
        value = value.strip()
        if value.lower() in ("true", "false"):
            meta[key.strip()] = value.lower() == "true"
        elif re.fullmatch(r"-?\d+", value):
            meta[key.strip()] = int(value)
        else:
            meta[key.strip()] = value
    return meta


def url_to_source(url: str) -> Path:
    if url == "":
        return CONTENT / "index.md"
    parts = url.strip("/").split("/")
    as_index = CONTENT.joinpath(*parts) / "index.md"
    if as_index.is_file():
        return as_index
    return CONTENT.joinpath(*parts[:-1]) / f"{parts[-1]}.md"


class Site:
    def __init__(self, *, file_links: bool = False, release: bool = False, analytics: bool = False) -> None:
        self.cfg = yaml.safe_load((ROOT / "site.yml").read_text(encoding="utf-8"))
        self.cfg["_analytics"] = analytics
        self.file_links = file_links
        self.release = release
        self.pages: dict[str, Page] = {}
        self.order: list[str] = []
        self.section_of: dict[str, str] = {}
        self.problems: list[str] = []
        self.warnings: list[str] = []
        self.glossary = self._load_glossary()
        self.measured = self._load_measured()
        self.data = _reference.load(DATA)
        self.now = _dt.date.today().isoformat()

    # -- inputs ----------------------------------------------------------
    def _load_glossary(self) -> dict:
        path = DATA / "glossary.yml"
        if not path.is_file():
            return {}
        entries = yaml.safe_load(path.read_text(encoding="utf-8")) or []
        return {slugify(e["term"]): e for e in entries}

    def _load_measured(self) -> dict:
        out = {}
        folder = CONTENT / "_measured"
        for p in sorted(folder.glob("*.json")) if folder.is_dir() else []:
            out[p.stem] = json.loads(p.read_text(encoding="utf-8"))
        return out

    def collect(self) -> None:
        for key, sec in self.cfg["sections"].items():
            for url in sec["pages"]:
                src = url_to_source(url)
                if not src.is_file():
                    self.problems.append(f"page listed in site.yml has no source: {url} ({src})")
                    continue
                meta, body = read_page(src)
                self.pages[url] = Page(url=url, source=src, meta=meta, body_md=body, section=key)
                self.order.append(url)
                self.section_of[url] = key
        # Pages outside the navigation: home, style guide, 404.
        for url, src in (("", CONTENT / "index.md"),
                         ("_styleguide/", CONTENT / "_styleguide" / "index.md"),
                         ("404/", CONTENT / "404.md")):
            if src.is_file() and url not in self.pages:
                meta, body = read_page(src)
                self.pages[url] = Page(url=url, source=src, meta=meta, body_md=body)

    # -- links -----------------------------------------------------------
    def rel(self, from_url: str, target: str) -> str:
        """``target`` is site-absolute ("/learn/03-scanning/#x", "/media/a.avif");
        the result is relative to the page at ``from_url`` ("" is the home page,
        a page URL ends in "/")."""
        if target.startswith(("http://", "https://", "mailto:", "#", "data:")):
            return target
        path, _, frag = target.lstrip("/").partition("#")
        folder = path == "" or path.endswith("/")
        if from_url == "404/":
            # Served at whatever depth was asked for: absolute from the root.
            out = "/" + self.cfg["base_url"].split("/", 3)[3] + path
        else:
            out = posixpath.relpath("/" + path if path else "/", "/" + from_url)
            if folder and not out.endswith("/"):
                out += "/"
            if self.file_links and folder:
                out += "index.html"
        return out + (f"#{frag}" if frag else "")

    # -- navigation ------------------------------------------------------
    def nav_for(self, url: str) -> dict:
        key = self.section_of.get(url)
        if key is None:
            return {}
        sec = self.cfg["sections"][key]
        items, last_group = [], None
        for i, u in enumerate(sec["pages"]):
            p = self.pages.get(u)
            if p is None:
                continue
            group = p.meta.get("group") if i else None
            items.append({"url": u, "title": p.nav_title, "current": u == url,
                          "index": i == 0, "num": p.meta.get("chapter"),
                          "group": group if group and group != last_group else None})
            if i:
                last_group = group
        also = sec.get("also")
        extra = None
        if also:
            s2 = self.cfg["sections"][also]
            extra = {"title": s2["title"], "items": [
                {"url": u, "title": self.pages[u].nav_title, "current": u == url,
                 "index": u == f"{also}/"} for u in s2["pages"] if u in self.pages]}
        return {"key": key, "title": sec["title"], "items": items,
                "numbered": sec.get("numbered", False), "also": extra}

    def neighbours(self, url: str):
        key = self.section_of.get(url)
        if key is None:
            return None, None
        seq = [u for u in self.cfg["sections"][key]["pages"] if u in self.pages]
        i = seq.index(url)
        prev = self.pages[seq[i - 1]] if i > 0 else None
        nxt = self.pages[seq[i + 1]] if i + 1 < len(seq) else None
        # Learn continues into Concepts' index is not useful; stop at the end.
        return prev, nxt

    def breadcrumb(self, url: str) -> list:
        crumbs = [{"title": "Home", "url": ""}]
        key = self.section_of.get(url)
        if key and url != f"{key}/":
            crumbs.append({"title": self.cfg["sections"][key]["title"], "url": f"{key}/"})
        if url.startswith("reference/interface/") and url != "reference/interface/":
            crumbs.append({"title": "The interface", "url": "reference/interface/"})
        return crumbs

    # -- rendering ---------------------------------------------------------
    def content_env(self, page: Page, media: MediaLibrary) -> Environment:
        # Comments use other delimiters: "{#id}" sets a heading's id in Markdown.
        env = Environment(undefined=StrictUndefined, autoescape=False, keep_trailing_newline=True,
                          comment_start_string="<#--", comment_end_string="--#>")
        link = lambda t: self.rel(page.url, t)  # noqa: E731

        def figure(shot_id, caption="", **kw):
            return media.figure(page.url, shot_id, caption, **kw)

        def clip(clip_id, caption="", **kw):
            return media.clip(page.url, clip_id, caption, **kw)

        def m(path: str):
            node = self.measured
            if path.split(".")[0] not in node:
                path = f'{page.meta.get("measured", "multimodal")}.{path}'
            for part in path.split("."):
                if not isinstance(node, dict) or part not in node:
                    self.problems.append(f"{page.url}: measured value not found: {path}")
                    return f"[{path}]"
                node = node[part]
            if isinstance(node, int):
                return f"{node:,}"
            return node

        def download(key: str, label: str = "Download", style: str = "primary"):
            d = self.cfg["downloads"].get(key)
            if d is None:
                self.problems.append(f"{page.url}: unknown download {key!r}")
                return ""
            if not d.get("url"):
                self.warnings.append(f"missing download link: {key} ({d.get('file')}) on /{page.url}")
                # Visible in a working build, so a review sees what is missing;
                # a release build refuses to run while any link is empty.
                return (f'<span class="btn btn--{style} btn--pending" aria-disabled="true">'
                        f'{d.get("file", key)}: link to come</span>')
            size = f'<span class="btn-meta">{d["size"]}</span>' if d.get("size") else ""
            return (f'<a class="btn btn--{style}" href="{d["url"]}" '
                    f'data-goatcounter-click="{d["goatcounter"]}" '
                    f'data-goatcounter-title="{html.escape(d.get("file", key))}">'
                    f'<svg viewBox="0 0 16 16" aria-hidden="true"><path d="M8 2.5v8m-3.5-3.5L8 10.5l3.5-3.5M3 13.5h10"/>'
                    f'</svg>{label}{size}</a>')

        def has_download(key: str) -> bool:
            return bool(self.cfg["downloads"].get(key, {}).get("url"))

        def key(spec: str):
            return _reference.kbd(spec)

        env.globals.update(
            figure=figure, clip=clip, m=m, download=download, has_download=has_download,
            key=key, link=link, site=self.cfg, version=self.cfg["version"],
            data=self.data, page=page.meta,
            ref=_reference.Macros(self.data, link, page.url, self.problems, self.glossary),
        )
        return env

    def render_page(self, page: Page, media: MediaLibrary) -> None:
        env = self.content_env(page, media)
        try:
            src = env.from_string(page.body_md).render()
        except Exception as exc:  # report with the page name
            raise RuntimeError(f"{page.source}: {exc}") from exc
        link = lambda t: self.rel(page.url, t)  # noqa: E731
        renderer = PageRenderer(self.glossary, link)
        try:
            out = renderer.render(src)
        except KeyError as exc:
            self.problems.append(f"{page.url}: {exc}")
            out = renderer.render(re.sub(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]", r"\1", src))
        body = _mac_click(self._absolutise(out.html, page.url))
        page.html, page.toc, page.ids = body, out.toc, out.ids
        page.text = _checks.visible_text(body)

    def _absolutise(self, body: str, url: str) -> str:
        """Site-absolute links in content ("/learn/...") become relative."""
        def repl(m):
            attr, target = m.group(1), m.group(2)
            if target.startswith("//"):
                return m.group(0)
            return f'{attr}="{self.rel(url, target)}"'
        return re.sub(r'\b(href|src|poster)="(/[^"]*)"', repl, body)

    def template_env(self) -> Environment:
        env = Environment(loader=FileSystemLoader(str(TEMPLATES)), undefined=StrictUndefined,
                          autoescape=False, trim_blocks=True, lstrip_blocks=True)
        env.filters["inline"] = inline
        return env

    def build(self) -> int:
        t0 = time.time()
        self.collect()
        if OUT.exists():
            shutil.rmtree(OUT)
        OUT.mkdir(parents=True)
        media = MediaLibrary(ROOT, lambda t: t)
        for page in self.pages.values():
            media.link = lambda t, u=page.url: self.rel(u, t)
            self.render_page(page, media)
        tenv = self.template_env()
        for page in self.pages.values():
            self._write(page, tenv)
        self._static()
        self._redirects(tenv)
        self._search_index()
        self._sitemap()
        self._check_cli_mentions()
        report = _checks.run(self, OUT, media)
        for msg in report.problems:
            self.problems.append(msg)
        for msg in report.warnings:
            self.warnings.append(msg)
        for shot_page, shot in media.missing:
            (self.problems if self.release else self.warnings).append(
                f"missing media: {shot} on /{shot_page}")
        unused = sorted(_unused_media(media))
        if unused:
            self.warnings.append(f"{len(unused)} media records not used by any page: "
                                 + ", ".join(unused[:12]) + (" ..." if len(unused) > 12 else ""))
        if self.release:
            self.problems += [w for w in self.warnings if w.startswith("missing download")]
        dt = time.time() - t0
        for w in self.warnings:
            print("warning:", w)
        for p in self.problems:
            print("PROBLEM:", p)
        print(f"built {len(self.pages)} pages in {dt:.1f} s; "
              f"{len(self.problems)} problems, {len(self.warnings)} warnings")
        return 1 if self.problems else 0

    def _write(self, page: Page, tenv: Environment) -> None:
        template = page.meta.get("template") or ("home" if page.url == "" else "doc")
        prev, nxt = self.neighbours(page.url)
        ctx = dict(
            site=self.cfg, page=page, meta=page.meta, nav=self.nav_for(page.url),
            prev=prev, next=nxt, crumbs=self.breadcrumb(page.url),
            link=lambda t: self.rel(page.url, t), header=self._header(page),
            version=self.cfg["version"], section=self.section_of.get(page.url),
            edit_url=(f'{self.cfg["docs_repo"]}/edit/{self.cfg["docs_repo_branch"]}/'
                      f'{page.source.relative_to(ROOT).as_posix()}'),
            issue_url=self._issue_url(page), now=self.now,
            canonical=self.cfg["base_url"] + page.url,
            data=self.data,
            is_section=any(sec.get("pages") and sec["pages"][0] == page.url
                           for sec in self.cfg["sections"].values()),
        )
        out_html = tenv.get_template(f"{template}.html").render(**ctx)
        dest = OUT / page.url / "index.html" if page.url not in ("", "404/") else (
            OUT / "index.html" if page.url == "" else OUT / "404.html")
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(out_html, encoding="utf-8")

    def _check_cli_mentions(self) -> None:
        """Every `bidsmgr-*` command and `--flag` a page names exists (plan 7.1)."""
        cli = self.data.get("cli")
        if not cli:
            self.warnings.append("no data/cli.json: command-line mentions not checked")
            return
        flags = {v["prog"]: {f for a in v["arguments"] for f in a["flags"]} for v in cli["verbs"]}
        every = set().union(*flags.values())
        for page in self.pages.values():
            if page.url.startswith("_styleguide"):
                continue
            # Text the app wrote itself (help tables, usage lines) is not checked.
            body = re.sub(r'<div class="table-wrap" data-generated>.*?</table></div>', "", page.html, flags=re.S)
            body = re.sub(r'<div class="code"[^>]*data-generated>.*?</pre></div>', "", body, flags=re.S)
            # A command and its flags are checked inside one piece of code: an
            # inline code span, or one line of a code block.
            pieces = []
            for block in re.findall(r"<pre[^>]*>(.*?)</pre>", body, flags=re.S):
                pieces += html.unescape(re.sub(r"<[^>]+>", "", block)).splitlines()
            body_wo_pre = re.sub(r"<pre[^>]*>.*?</pre>", "", body, flags=re.S)
            pieces += [html.unescape(re.sub(r"<[^>]+>", "", c))
                       for c in re.findall(r"<code[^>]*>(.*?)</code>", body_wo_pre, flags=re.S)]
            for line in pieces:
                for m in re.finditer(r"(?<![\w/\\.~-])(bidsmgr(?:-[a-z]+)?)\b(?![/\\]|\.\w|-)([^\n|]*)", line):
                    prog, rest = m.group(1), m.group(2)
                    if prog not in flags:
                        self.problems.append(f"{page.url}: unknown command {prog}")
                        continue
                    for f in re.findall(r"(?<![\w-])(--?[a-z][a-z0-9-]*)", rest):
                        if f not in flags[prog]:
                            self.problems.append(f"{page.url}: {prog} has no option {f}")
            # Commands named in prose must exist too.
            text = html.unescape(re.sub(r"<[^>]+>", "", body))
            for prog in set(re.findall(r"(?<![\w/\\.~-])(bidsmgr-[a-z]+)\b(?![/\\]|\.\w|-)", text)):
                if prog not in flags:
                    self.problems.append(f"{page.url}: unknown command {prog}")
            for code in re.findall(r"<code[^>]*>(--[a-z][a-z0-9-]*)", body):
                if code not in every:
                    self.problems.append(f"{page.url}: no command has the option {code}")

    def _issue_url(self, page: Page) -> str:
        from urllib.parse import quote
        title = quote(f"Documentation: {page.title}")
        body = quote(f"Page: {self.cfg['base_url']}{page.url}\n\nWhat is wrong or unclear:\n\n")
        return f"{self.cfg['docs_repo']}/issues/new?title={title}&body={body}"

    def _header(self, page: Page) -> list:
        current = self.section_of.get(page.url)
        if current == "concepts":
            current = "learn"
        out = []
        for key in self.cfg["header"]:
            sec = self.cfg["sections"][key]
            out.append({"key": key, "title": sec["title"], "url": f"{key}/",
                        "current": key == current})
        return out

    def _static(self) -> None:
        shutil.copytree(STATIC, OUT / "static")
        if MEDIA.is_dir():
            dest = OUT / "media"
            dest.mkdir()
            for p in MEDIA.iterdir():
                if p.suffix != ".json" and p.is_file():
                    shutil.copy2(p, dest / p.name)
        (OUT / ".nojekyll").write_text("")
        (OUT / "robots.txt").write_text(f"User-agent: *\nAllow: /\n\nSitemap: {self.cfg['base_url']}sitemap.xml\n")

    def _redirects(self, tenv: Environment) -> None:
        tpl = tenv.get_template("redirect.html")
        for old, spec in (self.cfg.get("redirects") or {}).items():
            if old == "index.html":
                continue
            target = spec["to"]
            # An old file (``about.html``) or an old folder page (``learn/x/``,
            # written as its ``index.html``); links are relative to it.
            from_url = old if old.endswith("/") else ""
            anchors = {k: self.rel(from_url, "/" + v) for k, v in (spec.get("anchors") or {}).items()}
            dest = OUT / (old + "index.html" if old.endswith("/") else old)
            if dest.exists():
                self.problems.append(f"redirect would overwrite a page: {old}")
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(tpl.render(target=self.rel(from_url, "/" + target), anchors=json.dumps(anchors),
                                       site=self.cfg, title=self.cfg["title"]), encoding="utf-8")

    def _search_index(self) -> None:
        entries = []
        for url in self.order:
            page = self.pages[url]
            sec = self.cfg["sections"][self.section_of[url]]["title"]
            for chunk in _checks.sections(page.html):
                text = re.sub(r"\s+", " ", chunk["text"]).strip()
                entries.append({"u": url + (f"#{chunk['id']}" if chunk["id"] else ""),
                                "p": page.title, "h": chunk["heading"], "s": sec,
                                "t": text[:600]})
        (OUT / "static" / "search-index.json").write_text(
            json.dumps(entries, separators=(",", ":"), ensure_ascii=False), encoding="utf-8")

    def _sitemap(self) -> None:
        urls = ["", *self.order]
        body = "".join(f"<url><loc>{html.escape(self.cfg['base_url'] + u)}</loc>"
                       f"<lastmod>{self.now}</lastmod></url>" for u in urls)
        (OUT / "sitemap.xml").write_text(
            '<?xml version="1.0" encoding="UTF-8"?>'
            f'<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">{body}</urlset>\n',
            encoding="utf-8")


def _unused_media(media: MediaLibrary):
    for p in MEDIA.glob("*.json") if MEDIA.is_dir() else []:
        if p.stem not in media.used and p.name != "manifest.json":
            yield p.stem


def serve(port: int, build_args: dict) -> None:
    import http.server
    import threading

    def snapshot():
        stamp = 0.0
        for base in (CONTENT, TEMPLATES, STATIC, MEDIA, DATA, ROOT / "site.yml", ROOT / "tools"):
            paths = [base] if base.is_file() else base.rglob("*")
            for p in paths:
                try:
                    stamp = max(stamp, p.stat().st_mtime)
                except OSError:
                    pass
        return stamp

    def watch():
        last = snapshot()
        while True:
            time.sleep(1.0)
            now = snapshot()
            if now != last:
                last = now
                try:
                    Site(**build_args).build()
                except Exception as exc:  # keep serving
                    print("build failed:", exc)

    threading.Thread(target=watch, daemon=True).start()

    class Handler(http.server.SimpleHTTPRequestHandler):
        def __init__(self, *a, **kw):
            super().__init__(*a, directory=str(OUT), **kw)

        def end_headers(self):
            self.send_header("Cache-Control", "no-store")
            super().end_headers()

        def log_message(self, *a):
            pass

    httpd = http.server.ThreadingHTTPServer(("127.0.0.1", port), Handler)
    print(f"serving http://127.0.0.1:{port}/ (rebuilds on change; Ctrl+C to stop)")
    httpd.serve_forever()


_SKIP_TAGS = ("code", "pre", "kbd", "h1", "h2", "h3", "h4", "a", "button", "script", "style", "summary")


def _mac_click(body: str) -> str:
    """The first "right-click" in a page's text gets "(Control-click on a
    Mac)"; the page's script hides it on Windows and Linux. Text inside
    headings, links, code and controls is left alone, and so is every
    attribute (an image's alt text)."""
    parts = re.split(r"(<[^>]+>)", body)
    depth = {t: 0 for t in _SKIP_TAGS}
    for i, part in enumerate(parts):
        if part.startswith("<"):
            m = re.match(r"<(/?)([a-zA-Z0-9]+)", part)
            if m and m.group(2).lower() in depth and not part.endswith("/>"):
                depth[m.group(2).lower()] += -1 if m.group(1) else 1
            continue
        if any(depth.values()):
            continue
        hit = re.search(r"\b[Rr]ight-click(?:ed|ing|s)?\b", part)
        if hit:
            end = hit.end()
            # after "right-click menu", note the whole phrase
            nxt = re.match(r" menu\b", part[end:])
            if nxt:
                end += nxt.end()
            parts[i] = (part[:end] + '<span class="mac-click"> (Control-click on a Mac)</span>' + part[end:])
            return "".join(parts)
    return body


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--serve", action="store_true", help="serve _site and rebuild on change")
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--release", action="store_true",
                    help="treat missing media and missing download links as errors")
    ap.add_argument("--file-links", action="store_true",
                    help="link to index.html files, so the site works from file://")
    ap.add_argument("--analytics", action="store_true",
                    help="include the GoatCounter counter (the deployed site; never local previews)")
    args = ap.parse_args(argv)
    build_args = {"file_links": args.file_links, "release": args.release, "analytics": args.analytics}
    rc = Site(**build_args).build()
    if args.serve:
        serve(args.port, build_args)
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
