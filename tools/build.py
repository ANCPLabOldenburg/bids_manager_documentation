"""Build the documentation site into ``_site/``.

    environments/docs/bin/python tools/build.py            # build and check
    environments/docs/bin/python tools/build.py --serve    # build, serve, rebuild on change
    environments/docs/bin/python tools/build.py --release  # fail on anything unfinished
    environments/docs/bin/python tools/build.py --file-links  # links that work from file://

Pages are Markdown in ``content/`` (front matter, then Jinja, then Markdown),
laid out by the templates in ``templates/``. Navigation and download links come
from ``site.yml``; reference tables from ``data/`` (generated from the
application by ``tools/reference``); figures and clips from ``media/``
(generated by ``tools/capture``); measured numbers from ``content/_measured``.
"""

